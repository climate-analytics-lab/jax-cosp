def gases(pressure, temperature, specific_humidity, freq):
    """Two-way gaseous attenuation (dB/km) through each volume.

    Parameters
    ----------
    pressure : array
        Pressure (Pa); any shape, broadcast with the other inputs.
    temperature : array
        Temperature (K).
    specific_humidity : array
        Specific humidity (kg/kg).
    freq : float
        Radar frequency (GHz), < 300.
    """
    f = freq
    pressure = jnp.asarray(pressure, dtype=jnp.result_type(float))
    th = 300.0 / jnp.asarray(temperature)
    specific_humidity = jnp.asarray(specific_humidity)
    e = specific_humidity * pressure / (specific_humidity + 0.622) / 1000.0
    p = pressure / 1000.0 - e
    e_th = e * th
    one_th = 1.0 - th
    pth3 = p * th**3
    eth35 = e * th**3.5

    # O2 resonance lines (term1). Line axis appended for broadcasting.
    x = th[..., None]
    p_ = p[..., None]
    gm = _A3 * (p_ * x ** (0.8 - _A4) + 1.1 * e_th[..., None])
    delt = _A5 * p_ * x**_A6
    lo = (_V0 - f) ** 2 + gm**2
    hi = (_V0 + f) ** 2 + gm**2
    # NOTE: the second bracket reproduces the Fortran verbatim, including its
    # use of `x` (i.e. `lo`) in both terms — the reference has
    # (aux3/x - aux4/x), not (aux3/lo - aux4/hi).
    fpp_o2 = ((1.0 / lo + 1.0 / hi) * (gm * f / _V0)
              - (delt * f / _V0) * ((_V0 - f) / lo - (_V0 + f) / lo))
    s_o2 = _A1 * pth3[..., None] * jnp.exp(_A2 * one_th[..., None])
    term1 = jnp.sum(fpp_o2 * s_o2, axis=-1)

    # Nonresonant O2 + pressure-induced N2 (term2).
    gm0 = 5.6e-3 * (p + 1.1 * e) * th**0.8
    a0 = 3.07e-4
    ap = 1.4 * (1 - 1.2 * f**1.5 * 1e-5) * 1e-10
    term2 = (2 * a0 * (gm0 * (1 + (f / gm0) ** 2) * (1 + (f / 60.0) ** 2)) ** (-1)
             + ap * p * th**2.5) * f * p * th**2

    # H2O resonance lines (term3).
    gm_w = _B3 * (p_ * x**0.8 + 4.8 * e_th[..., None])
    lo_w = (_V1 - f) ** 2 + gm_w**2
    hi_w = (_V1 + f) ** 2 + gm_w**2
    fpp_h2o = (1.0 / lo_w + 1.0 / hi_w) * (gm_w * f / _V1)
    s_h2o = _B1 * eth35[..., None] * jnp.exp(_B2 * one_th[..., None])
    term3 = jnp.sum(fpp_h2o * s_h2o, axis=-1)

    # H2O continuum (term4).
    term4 = (1.4e-6 * p + 5.41e-5 * e * th**3) * f * e * th**2.5

    npp = term1 + term2 + term3 + term4
    return 0.182 * f * npp
